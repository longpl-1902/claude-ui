// T07 / R-03, R-19: one controlled session driven through the manager with a FAKE child (no real process).
// The first block is the R-19 "no autonomous token spend" guarantee: stdin recorder shows only user-initiated frames.
import { describe, expect, it } from 'vitest'
import {
  DRAFT, SID, assistantMsg, canUseTool, createHarness, initMsg, messageStart, resultMsg, se, startSession, statusMsg, textDelta, textStart, thinkingStart
} from './harness'

describe('R-19 nothing is spawned or written until the user sends', () => {
  it('R-19 create() returns a draft with zero spawns and zero writes', () => {
    const h = createHarness()
    const info = h.mgr.create({ ...DRAFT })
    expect(info).toMatchObject({ state: 'draft', cwd: 'C:/Users/u/acme', accountId: 'acme', permissionMode: 'default', pendingPermissions: 0, queuedTurns: 0, slashCommands: [] })
    expect(info.id).toBe('c1')
    expect(info.pid).toBeUndefined()
    expect(h.spawnCalls).toHaveLength(0)
    expect(h.children).toHaveLength(0)
  })
  it('R-19 time passing on a draft spawns nothing (no warm-up, no timers)', () => {
    const h = createHarness()
    h.mgr.create({ ...DRAFT })
    h.advance(60 * 60_000)
    expect(h.spawnCalls).toHaveLength(0)
    expect(h.pendingTimers()).toBe(0)
  })
  it('R-19 draft setModel / setMode / list / get never spawn', () => {
    const h = createHarness()
    const { id } = h.mgr.create({ ...DRAFT })
    expect(h.mgr.setModel(id, 'opus').ok).toBe(true)
    expect(h.mgr.setMode(id, 'plan').ok).toBe(true)
    h.mgr.list()
    h.mgr.get(id)
    h.mgr.streamState(id)
    expect(h.spawnCalls).toHaveLength(0)
    expect(h.mgr.get(id)).toMatchObject({ model: 'opus', permissionMode: 'plan' })
  })
  it('R-19 one send -> exactly one spawn and exactly one user frame, nothing else on stdin', async () => {
    const h = createHarness()
    const { child } = await startSession(h, {}, 'hello world')
    expect(h.spawnCalls).toHaveLength(1)
    expect(child.frames()).toEqual([{ type: 'user', message: { role: 'user', content: 'hello world' }, parent_tool_use_id: null, session_id: '' }])
  })
  it('R-19 a whole turn of CLI output (init, status, deltas, assistant, result, control_response) causes no extra writes', async () => {
    const h = createHarness()
    const { child } = await startSession(h)
    child.emit(messageStart())
    child.emit(textStart())
    child.emit(textDelta('Hi'))
    child.emit(assistantMsg())
    child.emit({ type: 'control_response', response: { subtype: 'success', request_id: 'x', response: {} } })
    child.emit({ type: 'rate_limit_event', rate_limit_info: {} })
    child.emit(resultMsg())
    h.flush()
    expect(child.frames()).toHaveLength(1)
  })
  it('R-19 an idle session for hours writes nothing (no keep-alive) and sets no timers', async () => {
    const h = createHarness()
    const { child } = await startSession(h)
    child.emit(resultMsg())
    h.flush()
    h.advance(6 * 60 * 60_000)
    expect(child.frames()).toHaveLength(1)
    expect(h.pendingTimers()).toBe(0)
    expect(h.spawnCalls).toHaveLength(1)
  })
  it('R-19 no initialize control request is ever sent', async () => {
    const h = createHarness()
    const { child } = await startSession(h)
    expect(child.frames().some((f) => f.type === 'control_request')).toBe(false)
  })
  it('R-19 a crash does not retry: no respawn, no writes; only an explicit send starts it again', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    child.exit(1)
    h.advance(10 * 60_000)
    await h.settle()
    expect(h.spawnCalls).toHaveLength(1)
    expect(h.mgr.get(id)!.state).toBe('exited')
    const p = h.mgr.send(id, 'again')
    await h.settle()
    expect(h.spawnCalls).toHaveLength(2)
    h.lastChild().emit(initMsg())
    await p
  })
  it('R-19 setModel / setMode on a draft write nothing even after the later spawn (they become CLI args)', async () => {
    const h = createHarness()
    const { id } = h.mgr.create({ ...DRAFT })
    h.mgr.setModel(id, 'opus')
    h.mgr.setMode(id, 'acceptEdits')
    const p = h.mgr.send(id, 'go')
    await h.settle()
    const args = h.spawnCalls[0]!.args
    expect(args).toContain('--model')
    expect(args[args.indexOf('--model') + 1]).toBe('opus')
    expect(args[args.indexOf('--permission-mode') + 1]).toBe('acceptEdits')
    expect(h.lastChild().frames().filter((f) => f.type === 'control_request')).toHaveLength(0)
    h.lastChild().emit(initMsg())
    await p
  })
})

