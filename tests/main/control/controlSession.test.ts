describe('R-03 state machine and info', () => {
  it('R-03 draft -> starting on send; init fills session id, pid, model, slash commands, startedAt', async () => {
    const h = createHarness()
    const info = h.mgr.create({ ...DRAFT })
    const p = h.mgr.send(info.id, 'hi')
    await h.settle()
    expect(h.mgr.get(info.id)!.state).toBe('starting')
    expect(h.mgr.get(info.id)!.pid).toBe(h.lastChild().pid)
    h.lastChild().emit(initMsg())
    await p
    expect(h.mgr.get(info.id)).toMatchObject({ sessionId: SID, slashCommands: ['compact', 'review'], startedAt: '2026-11-19T10:00:00.000Z' })
  })
  it('R-03 status requesting -> busy; result -> idle with lastResult', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    expect(h.mgr.get(id)!.state).toBe('busy')
    child.emit(resultMsg())
    expect(h.mgr.get(id)).toMatchObject({ state: 'idle', lastResult: 'success' })
  })
  it('R-03 a second send while busy writes immediately and counts a queued turn; each result decrements', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    expect((await h.mgr.send(id, 'second')).ok).toBe(true)
    expect(child.frames().filter((f) => f.type === 'user')).toHaveLength(2)
    expect(h.mgr.get(id)!.queuedTurns).toBe(1)
    child.emit(resultMsg())
    expect(h.mgr.get(id)!.queuedTurns).toBe(0)
    child.emit(statusMsg())
    child.emit(resultMsg())
    expect(h.mgr.get(id)).toMatchObject({ queuedTurns: 0, state: 'idle' })
  })
  it('R-03 result is_error -> lastResult error; error_during_execution WITHOUT our interrupt -> error', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    child.emit(resultMsg({ subtype: 'error_during_execution', isError: true }))
    expect(h.mgr.get(id)!.lastResult).toBe('error')
    h.flush()
    expect(h.streams.flat().filter((e) => e.kind === 'turn-end').pop()).toMatchObject({ result: 'error' })
  })
  it('R-03 turn-end carries text, cost and denial count', async () => {
    const h = createHarness()
    const { child } = await startSession(h)
    child.emit(resultMsg({ text: 'All done', cost: 0.5, denials: 2 }))
    h.flush()
    expect(h.streams.flat().find((e) => e.kind === 'turn-end')).toMatchObject({ controlId: 'c1', result: 'success', text: 'All done', costUsd: 0.5, denials: 2 })
  })
  it('R-03 non-zero exit -> exited with exitCode and the last 2 KB of stderr (ANSI stripped) as error', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    child.emitStderr('x'.repeat(5000) + '\u001b[31mFATAL: bad thing\u001b[0m')
    child.exit(2)
    const info = h.mgr.get(id)!
    expect(info).toMatchObject({ state: 'exited', exitCode: 2 })
    expect(info.error).toContain('FATAL: bad thing')
    expect(info.error).not.toContain('\u001b')
    expect(info.error!.length).toBeLessThanOrEqual(2048)
  })
  it('R-03 exit code 0 -> exited without an error text', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    child.exit(0)
    expect(h.mgr.get(id)).toMatchObject({ state: 'exited', exitCode: 0 })
    expect(h.mgr.get(id)!.error).toBeUndefined()
  })
  it('R-03 a spawn error event ends the session with a notice and an error', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    child.fail(new Error('spawn ENOENT'))
    h.flush()
    expect(h.mgr.get(id)!.state).toBe('exited')
    expect(h.streams.flat().some((e) => e.kind === 'notice' && e.level === 'error')).toBe(true)
  })
  it('R-03 output split across chunks (and CRLF, and a multibyte char) is reassembled', async () => {
    const h = createHarness()
    const info = h.mgr.create({ ...DRAFT })
    const p = h.mgr.send(info.id, 'hi')
    await h.settle()
    const c = h.lastChild()
    const raw = Buffer.from(JSON.stringify(initMsg(SID, { cwd: 'C:/Users/u/acme-é' })) + '\r\n', 'utf8')
    c.emitRaw(raw.subarray(0, 30))
    c.emitRaw(raw.subarray(30, raw.length - 5))
    c.emitRaw(raw.subarray(raw.length - 5))
    await p
    expect(h.mgr.get(info.id)!.sessionId).toBe(SID)
  })
  it('R-03 garbage lines on stdout are ignored', async () => {
    const h = createHarness()
    const { id, child } = await startSession(h)
    child.emitRaw('not json at all\n{"type":\n\n')
    child.emit(resultMsg())
    expect(h.mgr.get(id)!.state).toBe('idle')
  })
  it('R-03 onChanged fires on state changes and can be unsubscribed', async () => {
    const h = createHarness()
    const seen: number[] = []
    const off = h.mgr.onChanged((l) => seen.push(l.length))
    const info = h.mgr.create({ ...DRAFT })
    expect(seen.length).toBeGreaterThan(0)
    off()
    const n = seen.length
    h.mgr.setMode(info.id, 'plan')
    expect(seen.length).toBe(n)
    expect(h.changes.length).toBeGreaterThan(0)
  })
})

